export function templateStyle(id, width) {
  const template = subtitleTemplates.find((t) => t.id === id);
  if (!template) throw Error("Plantilla desconocida");
  if (id === "impacto") return impactoStyle(width);
  const size = (ratio) =>
    Math.max(16, Math.min(180, Math.round(width * ratio)));
  return {
    ...impactoStyle(width),
    ...template.style,
    fontSize: size(template.size),
    secondFontSize: size(template.secondSize),
  };
}
